#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_blank() {
        let font = BitmapFont::new();
        let bitmap = font.render_char(' ').unwrap();
        assert!(bitmap.iter().all(|&b| b == 0));
    }

    #[test]
    fn a_is_not_blank() {
        let font = BitmapFont::new();
        let bitmap = font.render_char('A').unwrap();
        assert!(bitmap.iter().any(|&b| b != 0));
    }

    #[test]
    fn measure_empty() {
        let font = BitmapFont::new();
        assert_eq!(font.measure_text(""), (0, 16));
    }

    #[test]
    fn measure_hello() {
        let font = BitmapFont::new();
        assert_eq!(font.measure_text("Hello"), (40, 16));
    }

    #[test]
    fn out_of_range_returns_none() {
        let font = BitmapFont::new();
        assert!(font.render_char('\u{0100}').is_none());
    }

    #[test]
    fn cyrillic_upper_a_is_not_blank() {
        let font = BitmapFont::new();
        let bitmap = font.render_char('\u{0410}').unwrap(); // А
        assert!(bitmap.iter().any(|&b| b != 0));
    }

    #[test]
    fn cyrillic_lower_a_renders() {
        let font = BitmapFont::new();
        let bitmap = font.render_char('\u{0430}').unwrap(); // а
        assert!(bitmap.iter().any(|&b| b != 0));
    }

    #[test]
    fn cyrillic_yo_renders() {
        let font = BitmapFont::new();
        assert!(font.render_char('\u{0401}').is_some()); // Ё
        assert!(font.render_char('\u{0451}').is_some()); // ё
    }

    #[test]
    fn cyrillic_ya_renders() {
        let font = BitmapFont::new();
        assert!(font.render_char('\u{042F}').is_some()); // Я
        assert!(font.render_char('\u{044F}').is_some()); // я
    }
}
