/// Font module — provides both a bitmap fallback font and a fontdue-based TTF font.
///
/// The [`BitmapFont`] is a minimal 8x16 bitmap font for ASCII/Cyrillic.
/// The [`FontduFont`] uses an embedded DejaVu Sans Mono TTF for proportional rendering.

use fontdue;

/// Embedded TTF font data.
static TTF_SANS: &[u8] = include_bytes!("../assets/DejaVuSans-hmi.ttf");
static TTF_MONO: &[u8] = include_bytes!("../assets/DejaVuSansMono-hmi.ttf");
static TTF_BOLD: &[u8] = include_bytes!("../assets/DejaVuSans-Bold-hmi.ttf");

// ---------------------------------------------------------------------------
// FontduFont — TTF-based font rendering via fontdue (dual-font: sans + mono)
// ---------------------------------------------------------------------------

/// A font renderer backed by fontdue with both proportional (sans) and monospace fonts.
/// Sans is used by default; mono is used for code/pre elements.
pub struct FontduFont {
    sans: fontdue::Font,
    /// Parsed on first use: nothing draws monospace text yet, and fontdue keeps
    /// every glyph outline of a parsed font in memory.
    mono: std::sync::OnceLock<fontdue::Font>,
    /// Bold sans, parsed on first bold text for the same reason.
    bold: std::sync::OnceLock<fontdue::Font>,
    /// Rasterized glyphs by (char, size in 1/8 px, bold): a repaint redraws the
    /// same few dozen glyphs, and rasterizing them is most of a T113 frame.
    glyphs: std::sync::Mutex<std::collections::HashMap<(char, u32, bool), std::sync::Arc<(fontdue::Metrics, Vec<u8>)>>>,
}

/// Glyph cache entries kept before it is emptied (a page uses far fewer).
const GLYPH_CACHE_MAX: usize = 4096;

impl FontduFont {
    /// Create a new FontduFont with both embedded fonts.
    pub fn new() -> Self {
        let sans = fontdue::Font::from_bytes(
            TTF_SANS,
            fontdue::FontSettings::default(),
        )
        .expect("failed to parse embedded TTF sans font");
        FontduFont {
            sans,
            mono: std::sync::OnceLock::new(),
            bold: std::sync::OnceLock::new(),
            glyphs: std::sync::Mutex::new(std::collections::HashMap::new()),
        }
    }

    /// Vertical metrics at `font_size`: (ascent, descent, normal line height), as
    /// CSS `line-height: normal` uses them (DejaVu Sans: 0.928, 0.236, 1.164 em).
    pub fn line_metrics(&self, font_size: f32) -> (f32, f32, f32) {
        match self.sans.horizontal_line_metrics(font_size) {
            Some(m) => (m.ascent, -m.descent, m.new_line_size),
            None => (font_size * 0.928, font_size * 0.236, font_size * 1.164),
        }
    }

    /// Where the baseline of a line box of height `line_height` sits below its top:
    /// the leading is split evenly above and below the glyphs (CSS 2.1 §10.8.1).
    pub fn baseline_in_line(&self, font_size: f32, line_height: f32) -> f32 {
        let (ascent, descent, _) = self.line_metrics(font_size);
        (line_height - (ascent + descent)) / 2.0 + ascent
    }

    /// The process-wide instance: parsing both TTFs costs tens of ms on a Cortex-A7,
    /// so layout and paint share one instead of parsing per call.
    pub fn shared() -> &'static FontduFont {
        static FONT: std::sync::OnceLock<FontduFont> = std::sync::OnceLock::new();
        FONT.get_or_init(FontduFont::new)
    }

    /// Get the active font reference. Default is sans (proportional).
    fn font(&self) -> &fontdue::Font {
        &self.sans
    }

    /// The sans face for `font-weight` bold (600 and up) or regular.
    pub fn face(&self, bold: bool) -> &fontdue::Font {
        if !bold {
            return &self.sans;
        }
        self.bold.get_or_init(|| {
            fontdue::Font::from_bytes(TTF_BOLD, fontdue::FontSettings::default())
                .expect("failed to parse embedded TTF bold font")
        })
    }

    /// The rasterized glyph, from the cache when it has been drawn before.
    fn glyph(&self, ch: char, font_size: f32, bold: bool) -> std::sync::Arc<(fontdue::Metrics, Vec<u8>)> {
        let key = (ch, (font_size * 8.0).round() as u32, bold);
        let mut cache = self.glyphs.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(g) = cache.get(&key) {
            return g.clone();
        }
        if cache.len() >= GLYPH_CACHE_MAX {
            cache.clear();
        }
        let g = std::sync::Arc::new(self.face_for(ch, bold).rasterize(ch, font_size));
        cache.insert(key, g.clone());
        g
    }

    /// The face that draws `ch`: bold when asked for and it has the glyph (the
    /// bold subset is smaller), regular otherwise.
    fn face_for(&self, ch: char, bold: bool) -> &fontdue::Font {
        let face = self.face(bold);
        if bold && face.lookup_glyph_index(ch) == 0 {
            &self.sans
        } else {
            face
        }
    }

    /// Width of `text` in the regular or bold face.
    pub fn measure_text_in(&self, text: &str, font_size: f32, bold: bool) -> f32 {
        text.chars().map(|ch| self.face_for(ch, bold).metrics(ch, font_size).advance_width).sum()
    }

    /// Get the mono font reference (for code/pre elements).
    pub fn mono_font(&self) -> &fontdue::Font {
        self.mono.get_or_init(|| {
            fontdue::Font::from_bytes(TTF_MONO, fontdue::FontSettings::default())
                .expect("failed to parse embedded TTF mono font")
        })
    }

    /// Rasterize a single character at the given font size.
    /// Returns `(width, height, coverage_bitmap)` where coverage_bitmap
    /// contains one byte per pixel (0..255 alpha coverage).
    pub fn render_glyph(&self, ch: char, font_size: f32) -> (usize, usize, Vec<u8>) {
        let (metrics, bitmap) = self.font().rasterize(ch, font_size);
        (metrics.width, metrics.height, bitmap)
    }

    /// Measure the advance width and height for a single character.
    pub fn measure_char(&self, ch: char, font_size: f32) -> (f32, f32) {
        let metrics = self.font().metrics(ch, font_size);
        (metrics.advance_width, metrics.advance_height)
    }

    /// Measure total text dimensions (width = sum of advances, height = line height).
    pub fn measure_text(&self, text: &str, font_size: f32) -> (f32, f32) {
        let mut total_width: f32 = 0.0;
        for ch in text.chars() {
            let metrics = self.font().metrics(ch, font_size);
            total_width += metrics.advance_width;
        }
        let line_height = font_size * 1.2;
        (total_width, line_height)
    }

    /// Draw a single character into an RGBA buffer at (dest_x, dest_y).
    /// `stride` is the pixel-row width. `color` is [r, g, b, a].
    /// dest_y is the baseline-relative top of the line.
    pub fn draw_char(
        &self,
        buf: &mut [u8],
        stride: u32,
        dest_x: i32,
        dest_y: i32,
        ch: char,
        font_size: f32,
        color: [u8; 4],
    ) -> f32 {
        self.draw_char_in(buf, stride, dest_x, dest_y, ch, font_size, color, false)
    }

    #[allow(clippy::too_many_arguments)]
    fn draw_char_in(
        &self,
        buf: &mut [u8],
        stride: u32,
        dest_x: i32,
        dest_y: i32,
        ch: char,
        font_size: f32,
        color: [u8; 4],
        bold: bool,
    ) -> f32 {
        let glyph = self.glyph(ch, font_size, bold);
        let (metrics, bitmap) = (&glyph.0, &glyph.1);
        let m = metrics;

        // ymin is the offset from the baseline to the top of the glyph bitmap
        let glyph_top = dest_y + (font_size * 0.8) as i32 - metrics.height as i32 - m.ymin as i32;
        let glyph_left = dest_x + m.xmin as i32;

        for row in 0..metrics.height {
            for col in 0..metrics.width {
                let coverage = bitmap[row * metrics.width + col];
                if coverage == 0 {
                    continue;
                }
                let px = glyph_left + col as i32;
                let py = glyph_top + row as i32;
                if px < 0 || py < 0 || px >= stride as i32 {
                    continue;
                }
                let offset = ((py as u32 * stride + px as u32) * 4) as usize;
                if offset + 3 >= buf.len() {
                    continue;
                }
                // Alpha blend: coverage * color alpha
                let a = (coverage_lut()[coverage as usize] as u32 * color[3] as u32) / 255;
                let inv_a = 255 - a;
                buf[offset] =
                    ((color[0] as u32 * a + buf[offset] as u32 * inv_a) / 255) as u8;
                buf[offset + 1] =
                    ((color[1] as u32 * a + buf[offset + 1] as u32 * inv_a) / 255) as u8;
                buf[offset + 2] =
                    ((color[2] as u32 * a + buf[offset + 2] as u32 * inv_a) / 255) as u8;
                buf[offset + 3] = 255;
            }
        }

        m.advance_width
    }

    /// Draw a string into an RGBA buffer. Returns the total advance width.
    pub fn draw_text(
        &self,
        buf: &mut [u8],
        stride: u32,
        x: i32,
        y: i32,
        text: &str,
        font_size: f32,
        color: [u8; 4],
    ) -> f32 {
        self.draw_text_in(buf, stride, x, y, text, font_size, color, false)
    }

    /// `draw_text` in the regular or bold face.
    #[allow(clippy::too_many_arguments)]
    pub fn draw_text_in(
        &self,
        buf: &mut [u8],
        stride: u32,
        x: i32,
        y: i32,
        text: &str,
        font_size: f32,
        color: [u8; 4],
        bold: bool,
    ) -> f32 {
        let mut cx = x as f32;
        for ch in text.chars() {
            let advance = self.draw_char_in(buf, stride, cx as i32, y, ch, font_size, color, bold);
            cx += advance;
        }
        cx - x as f32
    }
}

/// Glyph coverage with a mild gamma (0.85): fontdue's linear coverage looks
/// thinner than browser text on the same font, and this narrows the gap.
fn coverage_lut() -> &'static [u8; 256] {
    static LUT: std::sync::OnceLock<[u8; 256]> = std::sync::OnceLock::new();
    LUT.get_or_init(|| std::array::from_fn(|i| ((i as f32 / 255.0).powf(0.85) * 255.0).round() as u8))
}

impl Default for FontduFont {
    fn default() -> Self {
        Self::new()
    }
}

