/// Minimal 8x16 bitmap font for rendering ASCII text without external font files.
///
/// Each character is stored as 16 bytes — one byte per row, 8 bits per pixel column.
/// Bit 7 (MSB) is the leftmost pixel; bit 0 is the rightmost.
/// Covers printable ASCII (32..=126).

pub struct BitmapFont {
    pub char_width: u32,
    pub char_height: u32,
}

impl Default for BitmapFont {
    fn default() -> Self {
        Self::new()
    }
}

impl BitmapFont {
    pub fn new() -> Self {
        BitmapFont {
            char_width: 8,
            char_height: 16,
        }
    }

    /// Returns the 16-byte bitmap for a printable ASCII character, or `None` if the
    /// character is outside the supported range.
    pub fn render_char(&self, c: char) -> Option<&'static [u8]> {
        let code = c as u32;

        // ASCII printable range 32..=126
        if (32..=126).contains(&code) {
            let index = (code - 32) as usize;
            let start = index * 16;
            let end = start + 16;
            if end > FONT_DATA.len() {
                return None;
            }
            return Some(&FONT_DATA[start..end]);
        }

        // Cyrillic uppercase А-Я: U+0410..=U+042F (32 chars)
        if (0x0410..=0x042F).contains(&code) {
            let index = (code - 0x0410) as usize;
            let start = index * 16;
            let end = start + 16;
            if end > CYRILLIC_DATA.len() {
                return None;
            }
            return Some(&CYRILLIC_DATA[start..end]);
        }

        // Cyrillic lowercase а-я: U+0430..=U+044F (32 chars)
        if (0x0430..=0x044F).contains(&code) {
            let index = (32 + (code - 0x0430)) as usize;
            let start = index * 16;
            let end = start + 16;
            if end > CYRILLIC_DATA.len() {
                return None;
            }
            return Some(&CYRILLIC_DATA[start..end]);
        }

        // Ё (U+0401)
        if code == 0x0401 {
            let start = 64 * 16; // after 32 upper + 32 lower
            let end = start + 16;
            if end > CYRILLIC_DATA.len() {
                return None;
            }
            return Some(&CYRILLIC_DATA[start..end]);
        }

        // ё (U+0451)
        if code == 0x0451 {
            let start = 65 * 16;
            let end = start + 16;
            if end > CYRILLIC_DATA.len() {
                return None;
            }
            return Some(&CYRILLIC_DATA[start..end]);
        }

        None
    }

    /// Measure the bounding box of a string in pixels: (width, height).
    /// Each character occupies `char_width` pixels; height is always `char_height`.
    pub fn measure_text(&self, text: &str) -> (u32, u32) {
        let count = text.chars().count() as u32;
        (count * self.char_width, self.char_height)
    }

    /// Rasterise a single character into caller-provided RGBA buffer at (dest_x, dest_y).
    /// `stride` is the pixel-row width of the destination buffer.
    /// `color` is [r, g, b, a] for the foreground.
    pub fn draw_char(
        &self,
        buf: &mut [u8],
        stride: u32,
        dest_x: u32,
        dest_y: u32,
        c: char,
        color: [u8; 4],
    ) {
        let bitmap = match self.render_char(c) {
            Some(b) => b,
            None => return,
        };
        for row in 0..16u32 {
            let byte = bitmap[row as usize];
            for col in 0..8u32 {
                if byte & (0x80 >> col) != 0 {
                    let px = dest_x + col;
                    let py = dest_y + row;
                    let offset = ((py * stride + px) * 4) as usize;
                    if offset + 3 < buf.len() {
                        // Simple alpha-over (source is opaque text)
                        let a = color[3] as u32;
                        let inv_a = 255 - a;
                        buf[offset] =
                            ((color[0] as u32 * a + buf[offset] as u32 * inv_a) / 255) as u8;
                        buf[offset + 1] =
                            ((color[1] as u32 * a + buf[offset + 1] as u32 * inv_a) / 255) as u8;
                        buf[offset + 2] =
                            ((color[2] as u32 * a + buf[offset + 2] as u32 * inv_a) / 255) as u8;
                        buf[offset + 3] = 255;
                    }
                }
            }
        }
    }

    /// Rasterise a whole string into an RGBA buffer.
    pub fn draw_text(
        &self,
        buf: &mut [u8],
        stride: u32,
        x: u32,
        y: u32,
        text: &str,
        color: [u8; 4],
    ) {
        let mut cx = x;
        for c in text.chars() {
            self.draw_char(buf, stride, cx, y, c, color);
            cx += self.char_width;
        }
    }
}

